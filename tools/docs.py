# ---------- css/bands-and-fields.css ----------
def rule_field(motif, ground):
    uri = G.data_uri(G.field_tile_svg(G.M[motif], ground))
    tw = G.M[motif]["cols"] * int(G.FIELD_MOD)
    th = G.M[motif]["rows"] * int(G.FIELD_MOD)
    ink, a = G.ink_for(ground)
    return (f"/* {motif} on {ground} — ink {ink} @ {a} */\n"
            f".field-{motif}-{ground}{{background-color:{G.GROUNDS[ground]};"
            f"background-image:url(\"{uri}\");"
            f"background-repeat:repeat;background-size:{tw}px {th}px}}\n")

def rule_band(cls, svg, w, h, repeat, bed=None):
    uri = G.data_uri(svg)
    bg = f"background-color:{bed};" if bed else ""
    return (f".{cls}{{height:{h}px;width:100%;{bg}"
            f"background-image:url(\"{uri}\");"
            f"background-repeat:{repeat};background-position:center;"
            f"background-size:{w}px {h}px}}\n")


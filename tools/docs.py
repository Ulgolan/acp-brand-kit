def tree():
    lines = []
    for d in ["sources", "motifs", "fields", "bands", "mixed", "css", "marks", "tools"]:
        fs = sorted(os.listdir(f"{OUT}/{d}"))
        fs = [f for f in fs if f != "__pycache__"]
        lines.append(f"\n### `/{d}/` — {len(fs)} files\n")
        if d == "fields":
            lines.append("Silhouette-dialect fields, one motif per file, on the six deployed grounds. "
                         "`.svg` is a 480x480 swatch carrying the tile as a `<pattern>`; `.png` is the "
                         "same at 2x (960x960).\n\n```\n")
            lines.append("\n".join(f"field_{m}_{{{','.join(G.GROUNDS)}}}.{{svg,png}}" for m in G.MOTIFS))
            lines.append("\n```\n")
        elif d == "mixed":
            lines.append("20 seeded Mixed Fields on ivory + abyss, even shuffle, silhouette dialect. "
                         "A seed produces one layout; that layout is rendered on both grounds.\n\n"
                         "**All 20 seeds reviewed and Commander-approved, 28 July 2026. The full set "
                         "is canon.**\n\n```\n"
                         "mix_s{1..20}_{ivory,abyss}.svg\ncontact-sheet.png\n```\n")
        elif d == "sources":
            lines.append("The canonical inputs. **Not build output — do not regenerate these.** "
                         "The loom reads them; everything else in this repo is derived from them.\n\n```\n"
                         + "\n".join(fs) + "\n```\n")
        else:
            lines.append("```\n" + "\n".join(fs) + "\n```\n")
    return "".join(lines)

